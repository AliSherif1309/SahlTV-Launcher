// Settings kept on the TV and small helpers around them.  (part of the Sahl TV home screen, split out of MainActivity)

internal fun MainActivity.list(key: String): MutableList<String> =
    (prefs.getString(key, "") ?: "").split("|").filter { it.isNotEmpty() }.toMutableList()

internal fun MainActivity.saveList(key: String, l: List<String>) = prefs.edit().putString(key, l.joinToString("|")).apply()

internal fun MainActivity.launches(pkg: String) = prefs.getInt("n_$pkg", 0)
